"""报告邮件推送：每天 23:59:59 给订阅用户发一封报告 —— 默认平时发当天日报，
周日发整周（周一..周日）的聚合周报，见下面第 ⑤ 条。

    23:59:59 这个时刻比它看起来麻烦，写之前先说清楚几个坑：

    ① 为什么是 23:59:59 而不是 00:00:00
       报告是「某一天的总结」，得在那一天过完时发。放到第二天 00:00:00
       发的话，「今天」已经变成新的一天了，算出来的是空报告。所以定时点
       必须停在当天最后一秒。

    ② 定时器不能只「睡到 23:59:59 然后发今天」
       服务器可能被重启、被挂起、时钟被 NTP 往回拨。醒来的时候如果已经
       是第二天 00:00:30 了，`date.today()` 就变成了新的一天，那这一天
       的报告就永远发不出去了。所以这里记的是**本次唤醒对应的那个时刻**
       （fire time，恒定是某天的 23:59:59），发哪一天由它决定，而不是由
       「现在几点」决定。睡过头也只会补发那一天，不会发错天。

    ③ 发过没有必须落库
       光靠内存里的标记，半夜重启一次就会重发。「同一天只发一封」最终由
       mail_log 表的 UNIQUE KEY 保证（见 db/schema.sql）。

    ④ 失败要留痕
       用户收不到邮件是会来问的，所以失败也写进 mail_log，并且日志里带上
       完整的 SMTP 报错。绝不允许「悄悄吞掉」。

    ⑤ 周日发的是周报，但那不改表结构
       报告种类（日报 / 周报）是「这一天是星期几」的**纯函数** —— 默认周日
       发周报，覆盖「以该天结尾的 7 天」的聚合（周一..周日），其余六天发当
       天的日报。所以**任何一天都只会长出一封邮件**，③ 里那个
       UNIQUE KEY (user_key, day) 依然成立：不用加 report_type 列，不用动
       线上那张表，也不用写迁移。哪天要是改成「周日同时发日报和周报」，
       这条才不成立，那时才必须把唯一键放宽成 (user_key, day, kind)。

关于多 worker：定时器是**进程内**的。用 `uvicorn --workers N` 启动时会有
N 个定时器同时到点，它们靠 mail_log 的唯一键互相兜底（重复的那封会在写
记录时撞键），但严格来说「查过没发」和「写记录」之间仍有竞态窗口，理论上
可能重复发一封。要么单 worker 跑（这个服务的量级完全够），要么关掉
进程内定时器（USAGETIME_MAIL_SCHEDULER=0），改由外部 cron 调
POST /api/v1/admin/daily-mail。

按「一条责任一个文件」拆开，依赖方向是单向的 report ← sender ← scheduler：
    report.py     正文渲染：秒数格式化、纯文本 / HTML 两个版本、拼成一封信
    sender.py     SMTP 发信，以及「给一个用户发某天」「给所有人发某天」两层
    scheduler.py  进程内的每日定时器（含 23:59:59 的解析和补发逻辑）

配置一律写成 `config.XXX` 属性访问，**不要** `from config import XXX` ——
测试是靠 `mock.patch.object(config, ...)` 换配置的，`from ... import` 会在导入
时把值复制成一份，patch 就静默失效了。
"""
